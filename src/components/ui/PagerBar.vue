<template>
  <div v-if="total > 0" class="flex flex-wrap items-center justify-between gap-3 border-t border-gray-100 px-4 py-3 sm:px-5">
    <div class="flex items-center gap-3 text-sm text-gray-600">
      <span>{{ from }}–{{ to }} of {{ total }}</span>
      <label v-if="perPageOptions.length" class="flex items-center gap-1.5">
        <span class="hidden sm:inline">Rows</span>
        <select :value="perPage" class="input w-auto py-1 text-sm" aria-label="Rows per page" @change="$emit('update:perPage', Number($event.target.value)); $emit('update:page', 1)">
          <option v-for="n in perPageOptions" :key="n" :value="n">{{ n }}</option>
        </select>
      </label>
    </div>
    <nav v-if="pages > 1" class="flex items-center gap-1" aria-label="Pages">
      <button type="button" class="pg" :disabled="page <= 1" aria-label="Previous page" @click="$emit('update:page', page - 1)"><ChevronLeft class="h-4 w-4" /></button>
      <template v-for="(p, i) in window" :key="i">
        <span v-if="p === '…'" class="px-1 text-gray-400">…</span>
        <button v-else type="button" class="pg" :class="p === page ? 'pg-on' : ''" :aria-current="p === page ? 'page' : undefined" @click="$emit('update:page', p)">{{ p }}</button>
      </template>
      <button type="button" class="pg" :disabled="page >= pages" aria-label="Next page" @click="$emit('update:page', page + 1)"><ChevronRight class="h-4 w-4" /></button>
    </nav>
  </div>
</template>

<script setup>
import { computed } from 'vue';
import { ChevronLeft, ChevronRight } from 'lucide-vue-next';

/** "11–20 of 120 · Rows [10]" and a pager showing the pages around the current one: 1 … 4 5 6 … 12 */
const props = defineProps({
  page: { type: Number, required: true },
  perPage: { type: Number, required: true },
  total: { type: Number, required: true },
  perPageOptions: { type: Array, default: () => [10, 25, 50, 100] },
});
defineEmits(['update:page', 'update:perPage']);

const pages = computed(() => Math.max(1, Math.ceil(props.total / props.perPage)));
const from = computed(() => (props.page - 1) * props.perPage + 1);
const to = computed(() => Math.min(props.page * props.perPage, props.total));
const window = computed(() => {
  const n = pages.value;
  const c = props.page;
  const set = [...new Set([1, n, c - 1, c, c + 1].filter((p) => p >= 1 && p <= n))].sort((a, b) => a - b);
  const out = [];
  set.forEach((p, i) => {
    if (i && p - set[i - 1] > 1) out.push('…');
    out.push(p);
  });
  return out;
});
</script>

