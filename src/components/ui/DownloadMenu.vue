<template>
  <div ref="root" class="relative">
    <button ref="trigger" type="button" class="dl-trigger" :disabled="disabled || busy" :aria-expanded="open" @click="open = !open">
      <Download class="h-4 w-4" /><span>{{ busy ? 'Preparing…' : label }}</span><ChevronDown class="h-3.5 w-3.5 opacity-60" />
    </button>
    <!-- In the page's top layer, so a neighbouring card can never cover it -->
    <Teleport to="body">
    <div v-if="open" ref="menu" class="dl-menu fixed z-[70] w-64 overflow-hidden rounded-xl border border-gray-200 bg-white shadow-xl" :style="menuPos">
      <div v-if="scopes.length" class="border-b border-gray-100 p-3">
        <label class="mb-1 block text-xs font-medium text-gray-500">{{ scopeLabel }}</label>
        <select v-model="scope" class="input py-1.5 text-sm">
          <option v-for="s in scopes" :key="s.value" :value="s.value">{{ s.label }}</option>
        </select>
      </div>
      <button type="button" class="dl-item" @click="pick('excel')">
        <FileSpreadsheet class="h-4 w-4 text-emerald-600" /><span><span class="block font-medium text-gray-900">Excel</span><span class="block text-xs text-gray-500">.xlsx, every column</span></span>
      </button>
      <button type="button" class="dl-item" @click="pick('pdf')">
        <FileText class="h-4 w-4 text-rose-600" /><span><span class="block font-medium text-gray-900">PDF</span><span class="block text-xs text-gray-500">A4 report to print or share</span></span>
      </button>
    </div>
    </Teleport>
  </div>
</template>

<script setup>
import { onBeforeUnmount, onMounted, ref, watch } from 'vue';
import { ChevronDown, Download, FileSpreadsheet, FileText } from 'lucide-vue-next';

/**
 * One "Download" button for every module. Emits download(format: 'excel' | 'pdf', scope).
 * scopes (optional): [{ value, label }], e.g. the whole year or one term.
 */
const props = defineProps({
  label: { type: String, default: 'Download' },
  scopes: { type: Array, default: () => [] },
  scopeLabel: { type: String, default: 'Include' },
  defaultScope: { type: [String, Number], default: null },
  busy: { type: Boolean, default: false },
  disabled: { type: Boolean, default: false },
});
const emit = defineEmits(['download']);
const open = ref(false);
const root = ref(null);
const trigger = ref(null);
const menu = ref(null);
const menuPos = ref({});
// Under the button, right-aligned with it; above it if there is no room below.
const place = () => {
  const r = trigger.value?.getBoundingClientRect();
  if (!r) return;
  const below = window.innerHeight - r.bottom > 240;
  menuPos.value = { right: `${Math.max(8, window.innerWidth - r.right)}px`, ...(below ? { top: `${r.bottom + 8}px` } : { bottom: `${window.innerHeight - r.top + 8}px` }) };
};
watch(open, (v) => { if (v) place(); });
const scope = ref(props.defaultScope ?? props.scopes[0]?.value ?? null);
watch(() => props.defaultScope, (v) => { if (v !== null && v !== undefined) scope.value = v; });
watch(() => props.scopes, (list) => { if (!list.some((s) => s.value === scope.value)) scope.value = props.defaultScope ?? list[0]?.value ?? null; });

const pick = (format) => {
  open.value = false;
  emit('download', format, scope.value);
};
const onDoc = (e) => { if (open.value && !root.value?.contains(e.target) && !menu.value?.contains(e.target)) open.value = false; };
const onScroll = () => { if (open.value) place(); };
const onKey = (e) => { if (e.key === 'Escape') open.value = false; };
onMounted(() => { document.addEventListener('mousedown', onDoc); document.addEventListener('keydown', onKey); window.addEventListener('scroll', onScroll, true); window.addEventListener('resize', onScroll); });
onBeforeUnmount(() => { document.removeEventListener('mousedown', onDoc); document.removeEventListener('keydown', onKey); window.removeEventListener('scroll', onScroll, true); window.removeEventListener('resize', onScroll); });
</script>

