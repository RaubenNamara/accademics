<template>
  <article class="space-y-4 text-sm text-gray-800">
    <!-- Header grid, as on the paper template -->
    <div class="overflow-x-auto">
      <table class="plan-grid w-full min-w-[480px]">
        <tbody>
          <tr v-for="(row, i) in headerRows" :key="i">
            <th>{{ row[0] }}</th><td :class="row[4] ? 'font-semibold' : ''">{{ row[1] || '-' }}</td>
            <th>{{ row[2] }}</th><td :class="row[5] ? 'font-semibold' : ''">{{ row[3] || '-' }}</td>
          </tr>
        </tbody>
      </table>
    </div>

    <section v-for="s in PLAN_SECTIONS" v-show="plan[s.key]" :key="s.key" :class="s.divider ? 'border-t border-gray-200 pt-4' : ''">
      <h4 class="font-bold text-gray-900">{{ s.label }}:</h4>
      <ul v-if="s.list" class="mt-1 list-disc space-y-0.5 pl-5">
        <li v-for="(line, i) in lines(plan[s.key])" :key="i">{{ line }}</li>
      </ul>
      <p v-else class="mt-1 whitespace-pre-line leading-relaxed">{{ plan[s.key] }}</p>
    </section>

    <section v-if="plan.procedure?.length" class="border-t border-gray-200 pt-4">
      <h4 class="text-base font-bold text-gray-900">Learning Procedure</h4>
      <div class="mt-2 overflow-x-auto">
        <table class="plan-grid w-full min-w-[520px]">
          <thead>
            <tr>
              <th class="w-16">Time per phase</th>
              <th>Teacher Activity: Observation, Conversation, Product</th>
              <th>Learners' Activity: Discovery, Explanatory, Analysis and Application</th>
            </tr>
          </thead>
          <tbody>
            <tr v-for="(p, i) in plan.procedure" :key="i">
              <td class="font-semibold">{{ p.minutes }} min</td>
              <td class="whitespace-pre-line">{{ p.teacher }}</td>
              <td class="whitespace-pre-line">{{ p.learners }}</td>
            </tr>
          </tbody>
        </table>
      </div>
    </section>

    <!-- Plans written before the procedure table -->
    <template v-else>
      <section v-for="s in legacy" v-show="plan[s.key]" :key="s.key">
        <h4 class="font-bold text-gray-900">{{ s.label }}:</h4>
        <p class="mt-1 whitespace-pre-line">{{ plan[s.key] }}</p>
      </section>
    </template>

    <section v-if="plan.assessment" class="border-t border-gray-200 pt-4">
      <h4 class="font-bold text-gray-900">Assessment Strategies:</h4>
      <p class="mt-1 whitespace-pre-line leading-relaxed">{{ plan.assessment }}</p>
    </section>

    <section class="border-t border-gray-200 pt-4">
      <h4 class="font-bold text-gray-900">{{ SELF_ASSESSMENT.label }}:</h4>
      <p class="mt-1 whitespace-pre-line" :class="plan.reflection ? '' : 'italic text-gray-500'">{{ plan.reflection || '(To be completed after the lesson.)' }}</p>
    </section>
  </article>
</template>

<script setup>
import { computed } from 'vue';
import { PLAN_SECTIONS, SELF_ASSESSMENT, durationText, longDate, timeRange } from './planMeta.js';

const props = defineProps({
  plan: { type: Object, required: true },
  showTeacher: Boolean,
});

const legacy = [
  { key: 'introduction', label: 'Introduction' },
  { key: 'development', label: 'Lesson development' },
  { key: 'conclusion', label: 'Conclusion' },
];
const lines = (v) => String(v || '').split(/\r?\n/).map((l) => l.replace(/^[•\-*]\s*/, '').trim()).filter(Boolean);

// [label, value, label, value, boldLeft, boldRight]
const headerRows = computed(() => {
  const p = props.plan;
  return [
    ['Week:', p.week_number ? `Week ${p.week_number}` : '', 'Date:', longDate(p.lesson_date), true, true],
    ['Subject:', p.subject_name, 'Time:', timeRange(p.start_time, p.duration_minutes)],
    ['Teacher:', p.teacher_name, 'Duration:', durationText(p.duration_minutes), true],
    ['Class:', p.full_class_name, 'Number of students:', p.learners ? `${p.learners} Learners` : '', true],
    ['Term:', p.term ? `Term ${p.term}` : '', 'Theme:', p.theme],
    ['Topic:', p.topic, 'Sub-Topic:', p.subtopic, true, true],
  ];
});
</script>

